/**
 * 검수 화면에 띄울 문구를 고른다.
 *
 * DB 함수가 올린 오류를 그대로 화면에 내보내면 두 가지가 샌다 (QA 1회차 발견 2·3번).
 * 1. 문장이 잘려 뜻을 잃는다 — `검수 대기 상태가 아니다: scheduled` 가
 *    화면에 "scheduled" 한 단어로 떴다
 * 2. DB 문구는 개발자용 반말이고, 앞으로 늘어날 오류가 영어일 수도 있다
 *
 * **아는 것만** 문구로 바꾸고 모르는 것은 일반 안내로 덮는다.
 * 모든 오류에 맞춤 문장을 붙이는 것이 목적이 아니라, 오류 내용을 화면으로
 * 흘리지 않는 것이 목적이다 (`qa/TRIAGE.md` 의 선 긋기).
 */

/** 모르는 오류가 왔을 때 내보낼 문구. 오류 내용은 여기에 절대 섞지 않는다. */
export const FALLBACK = '처리하지 못했습니다. 잠시 뒤 다시 시도해 주세요.'

const KNOWN: [RegExp, string][] = [
  [/운영자만 검수할 수 있다/, '운영자만 검수할 수 있습니다.'],
  [/없는 상품이다/, '이미 삭제되었거나 없는 상품입니다. 목록을 새로 고쳐 주세요.'],
  [
    /검수 대기(?: 상태가 아니다| 중인 상품이 아니다)/,
    '이미 처리된 상품입니다. 다른 곳에서 먼저 검수되었을 수 있습니다. 목록을 새로 고쳐 주세요.',
  ],
  [/없는 회차다/, '고른 회차를 찾을 수 없습니다. 목록을 새로 고쳐 주세요.'],
  [/이미 마감된 회차/, '이미 마감된 회차에는 배정할 수 없습니다. 다음 회차를 골라 주세요.'],
  [/반려 사유가 있어야 한다/, '반려 사유를 입력해 주세요. 판매자에게 그대로 전달됩니다.'],
]

export function adminErrorMessage(e: unknown): string {
  const raw = e instanceof Error ? e.message : String(e)
  for (const [pattern, message] of KNOWN) if (pattern.test(raw)) return message
  return FALLBACK
}
